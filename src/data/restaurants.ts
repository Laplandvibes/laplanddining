/**
 * Toimituksellisesti piilotetut listaukset. Maps voi näyttää lopettaneen
 * ravintolan avoimena kuukausia, joten sulkeminen on ihmisen päätös eikä
 * synkasta tuleva tieto. Perustelu on aina kommenttina overrides-tiedostossa.
 */
const hidden = new Set(
  Object.entries(restaurantOverrides)
    .filter(([, o]) => o.permanentlyClosed)
    .map(([placeId]) => placeId),
);

const merged: Restaurant[] = (mapsData as MapsRestaurant[])
  .filter((m) => !hidden.has(m.googlePlaceId))
  .map((m) => {
  const override = restaurantOverrides[m.googlePlaceId] ?? {};
  // Kuvarekisteri on ainoa kuvalähde. `m.photo` (Google Place Photo) jätetään
  // tarkoituksella huomiotta — ks. photoKind-kentän kommentti.
  const img = imageRegistry[m.slug];
  const usable = img && USABLE_KINDS.has(img.kind) ? img : undefined;
  return {
    ...m,
    ...override,
    photo: usable?.src,
    photoKind: usable?.kind as Restaurant['photoKind'],
    photoCommons: commonsCredit(usable),
    photoCredit: usable?.kind === 'partner' || usable?.kind === 'photo' ? usable.credit : undefined,
    ...menuFor(m.slug),
    // override may not include these required fields — preserve from maps
    name: m.name,
    /**
     * Kaupunki on ainoa "maps-kentta" jonka toimitus saa ylikirjoittaa.
     * Maps merkitsee osan ravintoloista kunnan mukaan (Gastropub Giitu ->
     * Inari) ja osan yksinkertaisesti vaarin (Kotahovi -> Posio, 114 km
     * paassa). Kaupunkisivu vaittaa otsikossaan "ravintolat kaupungissa X",
     * joten vaara arvo on julkaistu vaite eika vain lajitteluvirhe.
     * Peruste kirjataan aina koordinaatteina overrides-tiedostoon.
     */
    city: override.city ?? m.city,
    country: m.country,
    googleMapsUrl: m.googleMapsUrl,
    googlePlaceId: m.googlePlaceId,
    address: m.address,
    location: m.location,
    slug: m.slug,
    lastVerified: m.lastVerified,
    // override may flip topPick or upgrade partnership
    topPick: override.topPick ?? m.topPick,
    partnership: override.partnership ?? m.partnership,
    featured: override.topPick ?? m.topPick, // legacy alias
  };
});

/**
 * Käsin kuratoidut gems kulkevat saman kuvarekisterin läpi kuin muut.
 * Ilman tätä ne jäisivät ainoiksi kortteiksi ilman kuvamerkintää — ja niiden
 * vanhat .jpg-kuvat olivat tuntematonta alkuperää.
 */
const gemsWithImages: Restaurant[] = restaurantGems.map((g) => {
  const img = imageRegistry[g.slug];
  const usable = img && USABLE_KINDS.has(img.kind) ? img : undefined;
  return {
    ...g,
    ...menuFor(g.slug),
    photo: usable?.src ?? undefined,
    photoKind: usable?.kind as Restaurant['photoKind'],
    photoCommons: commonsCredit(usable),
    photoCredit: usable?.kind === 'partner' || usable?.kind === 'photo' ? usable.credit : undefined,
  };
});

/** All restaurants, merged (Maps + editorial overrides) plus hand-curated gems. */
export const restaurants: Restaurant[] = [...merged, ...gemsWithImages];

