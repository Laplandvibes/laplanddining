/** One restaurant per city, ordered as `cities` above. */
export function getTopPicksByCity(): Restaurant[] {
  return cities
    .map((city) => restaurants.find((r) => r.city === city && r.topPick))
    .filter((r): r is Restaurant => Boolean(r));
}

export function getRestaurantsByCity(city: string): Restaurant[] {
  return restaurants.filter((r) => r.city === city);
}

/** Legacy helper kept for /Home `Featured Restaurants` section — top picks of tier-1 cities. */
export function getFeaturedRestaurants(): Restaurant[] {
  const tier1 = ['Rovaniemi', 'Levi', 'Inari', 'Saariselkä', 'Kemi', 'Ylläs'];
  return tier1
    .map((c) => restaurants.find((r) => r.city === c && r.topPick))
    .filter((r): r is Restaurant => Boolean(r));
}

/**
 * Direct link to the Google reviews viewer for a Place. Always opens the
 * full reviews list (not just the place's main panel) so a "627 reviews"
 * pill click goes straight to the customer feedback the user wants to see.
 */
export function googleReviewsUrl(placeId: string): string {
  return `https://search.google.com/local/reviews?placeid=${encodeURIComponent(placeId)}`;
}

/** Partnership tier helpers for B2B logic + UI badges. */
export function partnershipBadge(tier: PartnershipTier): string | null {
  switch (tier) {
    case 'gold': return '★ Featured Partner';
    case 'premium': return 'Featured Partner';
    case 'verified': return 'Featured Listing';
    default: return null;
  }
}

