type ImageEntry = { src: string; kind: string; credit?: string };
const imageRegistry = restaurantImages as Record<string, ImageEntry>;

type MenuEntry = {
  url?: string; kind?: string; title?: string; evidence?: number;
  status?: string; reason?: string; note?: string; checkedAt: string;
};
const menuRegistry = restaurantMenus as Record<string, MenuEntry>;

/**
 * Ruokalistalinkki rekisterista. Vain `page` ja `pdf` kelpaavat; rivit joilla
 * on `status: 'none'` palauttavat tyhjan, jolloin korttiin ei tule nappia.
 *
 * Rekisteri on avainnettu slugilla samoin kuin kuvarekisteri, koska kasin
 * kuratoitujen gemsien googlePlaceId on tekaistu.
 */
function menuFor(slug: string): { menuUrl?: string; menuKind?: 'page' | 'pdf' } {
  const m = menuRegistry[slug];
  if (!m?.url || (m.kind !== 'page' && m.kind !== 'pdf')) return {};
  return { menuUrl: m.url, menuKind: m.kind };
}

/**
 * LaplandDining restaurant catalog.
 *
 * Source data layer (gitted, regenerated by `node scripts/sync-restaurants.mjs`):
 *   src/data/generated/restaurants-from-maps.json — 80 restaurants across 18
 *   Lapland cities, sourced from Google Places API (Text Search + Place Photos).
 *   Each restaurant has rating, review count, price level, opening hours,
 *   address, lat/lng, Maps URL, place ID, photo, last-verified date.
 *
 * Editorial layer (hand-maintained):
 *   src/data/restaurant-overrides.ts — per-Place-ID overrides for partnership
 *   tier (editorial/verified/premium/gold), curated descriptions, hand-picked
 *   menu highlights, dietary flags, cuisine labels.
 *
 * The merged output is what every page consumes via `restaurants` / `cities` /
 * `getTopPicksByCity()` helpers below.
 *
 * Re-sync: `cd laplanddining-new && node scripts/sync-restaurants.mjs`
 *   (Cost: ~$0.60 against the $200/month Google Maps free credit.)
 */

export type PartnershipTier = 'editorial' | 'verified' | 'premium' | 'gold';

export type Locale = 'en' | 'fi' | 'de' | 'ja' | 'es' | 'pt-BR' | 'zh-CN' | 'ko' | 'fr' | 'it' | 'nl' | 'sv';

/**
 * Localized string — either a single string (legacy = English only)
 * or an object with translations for each supported locale.
 */
export type LocalizedStr =
  | string
  | { en: string; fi: string; de: string; ja?: string; es?: string; 'pt-BR'?: string; 'zh-CN'?: string; ko?: string; fr?: string; it?: string; nl?: string; sv?: string };

/** Pick the right variant out of a LocalizedStr for the given locale. */
export function localizedStr(
  value: LocalizedStr | undefined,
  locale: Locale,
): string | undefined {
  if (value == null) return undefined;
  if (typeof value === 'string') return value;
  return value[locale] ?? value.en;
}

export interface Restaurant {
  // Maps-sourced (auto)
  name: string;
  city: string;
  country: string;
  rating?: number;
  reviewCount?: number;
  priceRange?: '€' | '€€' | '€€€' | '€€€€';
  editorialSummary?: string;       // Google's editorial blurb (only ~10% have it)
  reviewSummary?: string | null;    // Aggregated review summary (Pro tier, often null)
  reviewQuote?: string | null;      // Real customer quote, ~40-180 chars
  website?: string;
  googleMapsUrl: string;
  googlePlaceId: string;
  address: string;
  shortAddress?: string;            // e.g. "Valtakatu 20, Rovaniemi"
  location: { latitude: number; longitude: number };
  openingHours?: string[];          // weekday descriptions
  photo?: string;                   // /images/restaurants/{slug}.webp
  /**
   * Mistä kuva on peräisin. Ratkaisee kuvakaistan alareunan merkinnän.
   *   'partner'      — ravintolan oma og:image, merkintä "Kuva: <domain>"
   *   'illustration' — AI-kuvituskuva, merkintä "Kuvituskuva"
   * Google Place Photos EI ole sallittu lähde: Places API:n käytännöt kieltävät
   * sisällön tallentamisen ja vaativat kuvaajan tekijämerkinnän (vain place_id
   * saa säilöä). Poistettu käytöstä 2026-08-09.
   */
  photoKind?: 'partner' | 'illustration';
  photoCredit?: string;             // esim. "nili.fi" — vain partner-kuville
  /**
   * Ravintolan oma ruokalista. Lähde: generated/restaurant-menus.json, jonka
   * jokainen rivi on kuitattu käsin. 42/87 ravintolalla on linkki; lopuilla
   * rekisterissä on kirjattu syy miksi ei ole.
   */
  menuUrl?: string;
  menuKind?: 'page' | 'pdf';
  slug: string;
  lastVerified: string;             // YYYY-MM-DD
  primaryType?: string;
  types?: string[];

  // Editorial layer (manual overrides, optional)
  topPick: boolean;                 // shown in CityTopPicks home grid
  partnership: PartnershipTier;     // future B2B billing tier
  curatedDescription?: LocalizedStr; // overrides editorialSummary
  highlights?: LocalizedStr[];      // hand-picked signature items (localized; legacy string = EN-only)
  cuisine?: LocalizedStr;           // human-readable cuisine label
  type?: LocalizedStr;              // human-readable category
  menuHighlights?: { dish: string; price: string; note?: string }[];
  dietary?: ('vegan' | 'vegetarian' | 'gluten-free' | 'lactose-free')[];
  reservationPolicy?: string;
  featured?: boolean;               // legacy alias for topPick where used
}

