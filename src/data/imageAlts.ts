/** Kuvan alt lukijan kielellä; tuntematon kuva ⇒ '' (koristekuva). */
export function imageAlt(src: string | undefined, locale: Locale): string {
  if (!src) return '';
  const key = src.split('?')[0].replace(/\.(webp|avif|jpe?g|png)$/i, '').replace(/-(800|1200|1280|1920|2560)$/, '');
  const alt = IMAGE_ALTS[key];
  return alt ? alt[locale] ?? alt.en : '';
}
