/**
 * Tekijätieto kuvan polusta. Normalisoi `?v=`-tunnisteen (version-images.mjs lisää sen
 * buildissa), päätteen ja kokoliitteen (-800/-1280/-1920/-2560).
 */
export function creditFor(src?: string): PhotoCreditEntry | undefined {
  if (!src) return undefined;
  const key = src.split('?')[0].replace(/\.(webp|avif|jpe?g|png)$/i, '').replace(/-(800|1280|1920|2560)$/, '');
  return PHOTO_CREDITS[key];
}

